package hue.captains.singapura.js.homing.conformance.workbench;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;

/**
 * The workbenches' first states in the split grid, as their page has them:
 * {@code WORKBENCH_ARRANGEMENTS}, by kind, generated from {@link WorkbenchWorkspaces} - laid out
 * when the page writes a log that holds nothing yet.
 */
public record WorkbenchArrangementsModule() implements EsModule<WorkbenchArrangementsModule>, SelfContent {

    public static final WorkbenchArrangementsModule INSTANCE = new WorkbenchArrangementsModule();

    public record WORKBENCH_ARRANGEMENTS() implements Exportable._Constant<WorkbenchArrangementsModule> {}

    @Override public ImportsFor<WorkbenchArrangementsModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<WorkbenchArrangementsModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new WORKBENCH_ARRANGEMENTS())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by WorkbenchArrangementsModule from WorkbenchWorkspaces - do not hand-edit.",
                WorkbenchWorkspaces.SITE.arrangementsJs("WORKBENCH_ARRANGEMENTS"));
    }
}
