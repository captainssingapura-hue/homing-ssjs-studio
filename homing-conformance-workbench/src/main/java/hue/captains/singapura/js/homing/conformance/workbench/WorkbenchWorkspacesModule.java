package hue.captains.singapura.js.homing.conformance.workbench;

import hue.captains.singapura.js.homing.core.DomModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;

/**
 * The workbenches as their page has them: {@code WORKBENCH_WORKSPACES}, each one's manifest by its
 * kind - its widget kinds and its root parties - generated from {@link WorkbenchWorkspaces#SITE}.
 * A DOM module, though it touches no DOM: it imports the widgets' classes.
 */
public record WorkbenchWorkspacesModule() implements DomModule<WorkbenchWorkspacesModule>, SelfContent {

    public static final WorkbenchWorkspacesModule INSTANCE = new WorkbenchWorkspacesModule();

    public record WORKBENCH_WORKSPACES() implements Exportable._Constant<WorkbenchWorkspacesModule> {}

    @Override public ImportsFor<WorkbenchWorkspacesModule> imports() { return WorkbenchWorkspaces.SITE.manifestsImports(); }

    @Override
    public ExportsOf<WorkbenchWorkspacesModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new WORKBENCH_WORKSPACES())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by WorkbenchWorkspacesModule from WorkbenchWorkspaces.SITE - do not hand-edit: each workbench's kinds, and its root parties.",
                WorkbenchWorkspaces.SITE.manifestsJs("WORKBENCH_WORKSPACES"));
    }
}
