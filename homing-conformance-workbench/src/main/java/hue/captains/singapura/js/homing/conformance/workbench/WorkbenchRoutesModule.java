package hue.captains.singapura.js.homing.conformance.workbench;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;
import java.util.stream.Collectors;

/**
 * The feeds' routes, as the page has them: {@code WORKBENCH_ROUTES}, generated from the Java
 * feeds' own - so a widget and the feed it reads cannot disagree on where.
 */
public record WorkbenchRoutesModule() implements EsModule<WorkbenchRoutesModule>, SelfContent {

    public static final WorkbenchRoutesModule INSTANCE = new WorkbenchRoutesModule();

    public record WORKBENCH_ROUTES() implements Exportable._Constant<WorkbenchRoutesModule> {}

    @Override public ImportsFor<WorkbenchRoutesModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<WorkbenchRoutesModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new WORKBENCH_ROUTES())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        String routes = WorkbenchFeedsModule.ROUTES.stream().map(r -> r[0] + ": \"" + r[1] + "\"").collect(Collectors.joining(", "));
        return List.of("// Generated by WorkbenchRoutesModule from the workbench's feeds - do not hand-edit.",
                "const WORKBENCH_ROUTES = Object.freeze({ " + routes + " });");
    }
}
