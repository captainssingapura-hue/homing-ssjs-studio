package hue.captains.singapura.js.homing.conformance.workbench;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;

/** The group the workbenches are filed in, as their page provides it to the directory: {@code WORKBENCH_GROUPS}, generated from {@link WorkbenchWorkspaces#GROUPS}. */
public record WorkbenchGroupsModule() implements EsModule<WorkbenchGroupsModule>, SelfContent {

    public static final WorkbenchGroupsModule INSTANCE = new WorkbenchGroupsModule();

    public record WORKBENCH_GROUPS() implements Exportable._Constant<WorkbenchGroupsModule> {}

    @Override public ImportsFor<WorkbenchGroupsModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<WorkbenchGroupsModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new WORKBENCH_GROUPS())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by WorkbenchGroupsModule from WorkbenchWorkspaces.GROUPS - do not hand-edit.", WorkbenchWorkspaces.SITE.groupsJs("WORKBENCH_GROUPS"));
    }
}
